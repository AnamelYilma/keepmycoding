'use client';

import { useState, useMemo, useRef, useEffect } from 'react';
import {
  Terminal,
  CheckCircle2,
  ArrowRight,
  RotateCcw,
  BookOpen,
  ChevronLeft,
  ChevronDown,
  Check,
} from 'lucide-react';
import { validateRawChallenge } from '@/lib/parser/challenge-validator';
import { ValidationFeedback } from './ValidationFeedback';
import { SAMPLE_CHALLENGES } from '@/lib/sample-challenges';
import { Challenge } from '@/lib/types/challenge';

interface PasteChallengeBoxProps {
  onStartChallenge: (challenge: Challenge) => void;
  onGoToPrompt?: () => void;
}

export function PasteChallengeBox({ onStartChallenge, onGoToPrompt }: PasteChallengeBoxProps) {
  const [rawText, setRawText] = useState<string>('');
  const [selectedSampleId, setSelectedSampleId] = useState<string>('');
  const [isSampleDropdownOpen, setIsSampleDropdownOpen] = useState<boolean>(false);
  const dropdownRef = useRef<HTMLDivElement>(null);
  const textareaRef = useRef<HTMLTextAreaElement>(null);
  const gutterRef = useRef<HTMLDivElement>(null);

  // Close dropdown on click outside or escape key
  useEffect(() => {
    function handleClickOutside(event: MouseEvent) {
      if (dropdownRef.current && !dropdownRef.current.contains(event.target as Node)) {
        setIsSampleDropdownOpen(false);
      }
    }
    function handleKeyDown(event: KeyboardEvent) {
      if (event.key === 'Escape') {
        setIsSampleDropdownOpen(false);
      }
    }
    if (isSampleDropdownOpen) {
      document.addEventListener('mousedown', handleClickOutside);
      document.addEventListener('keydown', handleKeyDown);
    }
    return () => {
      document.removeEventListener('mousedown', handleClickOutside);
      document.removeEventListener('keydown', handleKeyDown);
    };
  }, [isSampleDropdownOpen]);

  // Live validation
  const validation = useMemo(() => {
    if (!rawText.trim()) return null;
    return validateRawChallenge(rawText);
  }, [rawText]);

  const handleSelectSample = (sampleId: string) => {
    setSelectedSampleId(sampleId);
    setIsSampleDropdownOpen(false);
    const sample = SAMPLE_CHALLENGES.find((s) => s.id === sampleId);
    if (sample) {
      setRawText(sample.raw);
    }
  };

  const handleQuickSample = () => {
    if (SAMPLE_CHALLENGES.length > 0) {
      setSelectedSampleId(SAMPLE_CHALLENGES[0].id);
      setRawText(SAMPLE_CHALLENGES[0].raw);
    }
  };

  const handleQuickLaunchSample = () => {
    if (SAMPLE_CHALLENGES.length > 0) {
      const sample = SAMPLE_CHALLENGES[0];
      setSelectedSampleId(sample.id);
      setRawText(sample.raw);
      const val = validateRawChallenge(sample.raw);
      if (val.valid && val.challenge) {
        onStartChallenge(val.challenge);
      }
    }
  };

  const handleStart = () => {
    if (validation && validation.valid && validation.challenge) {
      onStartChallenge(validation.challenge);
    }
  };

  const handleClear = () => {
    setRawText('');
  };

  const handleScroll = () => {
    if (gutterRef.current && textareaRef.current) {
      gutterRef.current.scrollTop = textareaRef.current.scrollTop;
    }
  };

  const isEmpty = !rawText.trim();
  const isValid = validation?.valid === true;

  const linesCount = useMemo(() => {
    if (!rawText) return 12;
    const count = rawText.split('\n').length;
    return Math.max(count, 12);
  }, [rawText]);

  return (
    <div className="bg-[#11131A] border border-white/10 rounded-2xl shadow-2xl relative overflow-hidden">
      {/* 1. Header Row: Title & Action Summary */}
      <div className="p-6 sm:p-7 border-b border-white/8 space-y-4">
        <div className="flex items-center gap-3">
          <div className="w-9 h-9 rounded-xl bg-[#090A0F] border border-white/10 flex items-center justify-center text-[#88BDA4] shadow-sm">
            <Terminal className="w-4 h-4" aria-hidden="true" />
          </div>
          <div>
            <h2 className="text-base sm:text-lg font-semibold text-zinc-100">
              Input Challenge Block
            </h2>
            <p className="text-xs text-zinc-400 mt-0.5 leading-relaxed">
              Paste the tagged challenge output generated by your AI, or try a built-in sample.
            </p>
          </div>
        </div>

        {/* 2. Utilitarian Action Toolbar: Dedicated toolbar line with unified button styling */}
        <div className="flex flex-wrap items-center justify-between gap-2.5 pt-2 border-t border-white/5">
          <div className="flex items-center gap-2 flex-wrap">
            <button
              type="button"
              onClick={handleQuickLaunchSample}
              className="inline-flex items-center gap-1.5 px-3.5 py-1.5 rounded-lg bg-[#88BDA4] hover:bg-[#9cd1b8] text-[#090A0F] font-semibold text-xs transition-all cursor-pointer shadow-sm active:scale-[0.98] focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-[#88BDA4]"
            >
              <BookOpen className="w-3.5 h-3.5 text-[#090A0F]" aria-hidden="true" />
              <span>Launch Sample</span>
            </button>

            <button
              type="button"
              onClick={handleQuickSample}
              className="inline-flex items-center gap-1.5 px-3.5 py-1.5 rounded-lg bg-[#090A0F] hover:bg-[#151821] text-zinc-300 border border-white/10 text-xs font-medium transition-all cursor-pointer focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-[#88BDA4]"
            >
              <BookOpen className="w-3.5 h-3.5 text-zinc-400" aria-hidden="true" />
              <span>Paste Sample</span>
            </button>

            {/* Custom Popover Dropdown */}
            <div className="relative" ref={dropdownRef}>
              <button
                type="button"
                onClick={() => setIsSampleDropdownOpen((prev) => !prev)}
                aria-expanded={isSampleDropdownOpen}
                aria-haspopup="listbox"
                aria-label="Select sample challenge"
                className={`inline-flex items-center gap-2 rounded-lg px-3 py-1.5 text-xs font-medium transition-all cursor-pointer border ${
                  isSampleDropdownOpen
                    ? 'bg-[#1b202c] border-[#88BDA4]/60 text-zinc-100 ring-1 ring-[#88BDA4]/40'
                    : 'bg-[#090A0F] border-white/10 text-zinc-300 hover:border-white/20 hover:text-zinc-100'
                }`}
              >
                <span className="max-w-[130px] truncate">
                  {selectedSampleId
                    ? SAMPLE_CHALLENGES.find((s) => s.id === selectedSampleId)?.label.split(' - ')[0] || 'Selected'
                    : 'More Samples'}
                </span>
                <ChevronDown
                  className={`w-3.5 h-3.5 text-zinc-400 transition-transform duration-200 ${
                    isSampleDropdownOpen ? 'rotate-180 text-[#88BDA4]' : ''
                  }`}
                  aria-hidden="true"
                />
              </button>

              {/* Popover Dropdown Menu */}
              {isSampleDropdownOpen && (
                <div
                  role="listbox"
                  aria-label="Sample challenges"
                  className="absolute left-0 sm:left-auto sm:right-0 top-full mt-2 w-72 sm:w-80 rounded-xl bg-[#0e1017] border border-white/15 p-1.5 shadow-2xl z-50 backdrop-blur-xl animate-in fade-in zoom-in-95 duration-150"
                >
                  <div className="px-2.5 py-1.5 text-[10px] font-mono uppercase tracking-wider text-zinc-400 border-b border-white/8 mb-1">
                    Preset Challenges
                  </div>
                  <div className="space-y-1 max-h-64 overflow-y-auto pr-0.5">
                    {SAMPLE_CHALLENGES.map((sample) => {
                      const isSelected = selectedSampleId === sample.id;
                      return (
                        <button
                          key={sample.id}
                          type="button"
                          role="option"
                          aria-selected={isSelected}
                          onClick={() => handleSelectSample(sample.id)}
                          className={`w-full text-left px-3 py-2.5 rounded-lg text-xs transition-colors cursor-pointer flex items-start justify-between gap-2.5 ${
                            isSelected
                              ? 'bg-[#1b202c] text-white border border-[#88BDA4]/30'
                              : 'text-zinc-300 hover:bg-[#151821] hover:text-white'
                          }`}
                        >
                          <div className="flex-1 min-w-0">
                            <div className="font-medium text-zinc-100 truncate text-xs">
                              {sample.label}
                            </div>
                            <div className="flex items-center gap-2 mt-1 font-mono text-[10px] text-zinc-400">
                              <span className="text-[#88BDA4]">Track {sample.track}</span>
                              <span>•</span>
                              <span>Level {sample.level}</span>
                              <span>•</span>
                              <span>{sample.language}</span>
                            </div>
                          </div>
                          {isSelected && (
                            <Check className="w-4 h-4 text-[#88BDA4] shrink-0 mt-0.5" aria-hidden="true" />
                          )}
                        </button>
                      );
                    })}
                  </div>
                </div>
              )}
            </div>
          </div>

          <button
            type="button"
            onClick={handleClear}
            disabled={isEmpty}
            className="inline-flex items-center gap-1.5 px-2.5 py-1.5 rounded-lg bg-[#090A0F] text-zinc-400 hover:text-zinc-200 border border-white/10 hover:border-white/20 disabled:opacity-30 disabled:hover:text-zinc-400 transition-colors text-xs cursor-pointer focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-[#88BDA4]"
            title="Clear textarea"
            aria-label="Clear challenge input"
          >
            <RotateCcw className="w-3.5 h-3.5" aria-hidden="true" />
            <span>Clear</span>
          </button>
        </div>
      </div>

      {/* 3. Editor Surface with Line Numbers */}
      <div className="p-6 sm:p-7 space-y-4">
        <div className="relative flex rounded-xl border border-white/10 bg-[#07080C] focus-within:border-[#88BDA4]/60 focus-within:ring-1 focus-within:ring-[#88BDA4]/30 transition-all overflow-hidden shadow-inner">
          {/* Gutter */}
          <div
            ref={gutterRef}
            aria-hidden="true"
            className="w-12 py-4 pl-2 pr-3.5 font-mono text-[11px] font-medium text-zinc-500 bg-[#10131c] border-r border-white/8 select-none text-right overflow-hidden shrink-0 leading-[1.625rem]"
          >
            {Array.from({ length: linesCount }, (_, i) => (
              <div key={i + 1}>{i + 1}</div>
            ))}
          </div>

          {/* Textarea */}
          <textarea
            ref={textareaRef}
            onScroll={handleScroll}
            rows={12}
            value={rawText}
            onChange={(e) => setRawText(e.target.value)}
            aria-label="Raw challenge specification block"
            placeholder={`---METADATA---
track: 1
level: 2
type: Fix
editableLanguage: typescript
editableFiles: src/token-validator.ts

---TASK---
Describe task specifications here...

---FILE: src/token-validator.ts---
// Code to inspect and modify...

---TESTS---
// Test cases...

---REFERENCE---
// Correct reference answer...`}
            className="w-full bg-[#07080C] p-4 text-xs font-mono text-zinc-100 placeholder:text-zinc-500 focus:outline-none resize-y leading-[1.625rem] min-h-[280px]"
            spellCheck={false}
            onKeyDown={(e) => {
              if ((e.ctrlKey || e.metaKey) && e.key === 'Enter') {
                e.preventDefault();
                if (isValid && validation?.challenge) {
                  handleStart();
                }
              }
            }}
          />
        </div>

        {/* Live Validation Bar */}
        {isEmpty ? (
          <div className="p-3.5 rounded-xl bg-[#0d0f17] border border-white/8 text-xs text-zinc-300 flex flex-col sm:flex-row sm:items-center justify-between gap-2 shadow-inner">
            <span className="flex items-center gap-2">
              <span className="inline-block w-2 h-2 rounded-full bg-zinc-600 animate-pulse" />
              <span>Awaiting challenge input. Paste AI output above or click &quot;Launch Sample&quot;.</span>
            </span>
            <span className="font-mono text-[11px] text-zinc-400 font-medium">0 characters</span>
          </div>
        ) : isValid && validation.challenge ? (
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 p-4 rounded-xl bg-[#0c1214] border border-[#88BDA4]/40 text-xs shadow-md">
            <div className="flex items-center gap-3">
              <div className="w-7 h-7 rounded-lg bg-[#88BDA4]/15 border border-[#88BDA4]/40 flex items-center justify-center text-[#88BDA4] shrink-0">
                <CheckCircle2 className="w-4 h-4 text-[#88BDA4]" aria-hidden="true" />
              </div>
              <div className="flex items-center gap-2 sm:gap-2.5 text-zinc-200 font-mono text-xs flex-wrap">
                <span className="text-[#88BDA4] font-semibold">Valid Challenge</span>
                <span className="text-zinc-600">|</span>
                <span className="rounded-md bg-white/5 border border-white/10 px-2 py-0.5 text-zinc-200">
                  Track {validation.challenge.metadata.track}
                </span>
                <span className="rounded-md bg-[#88BDA4]/10 border border-[#88BDA4]/25 px-2 py-0.5 text-[#88BDA4] font-medium">
                  Level {validation.challenge.metadata.level}
                </span>
                <span className="rounded-md bg-white/5 border border-white/10 px-2 py-0.5 text-zinc-300">
                  {validation.challenge.metadata.editableLanguage}
                </span>
                <span className="text-zinc-400">
                  {validation.challenge.files.length} {validation.challenge.files.length === 1 ? 'file' : 'files'}
                </span>
              </div>
            </div>

            <button
              type="button"
              onClick={handleStart}
              className="inline-flex items-center gap-1.5 px-4 py-2 rounded-lg bg-[#171a24] hover:bg-[#1f2330] text-[#88BDA4] border border-[#88BDA4]/30 font-mono text-xs font-semibold transition-all cursor-pointer self-start sm:self-auto focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-[#88BDA4]"
            >
              <span>Launch Workspace</span>
              <ArrowRight className="w-3.5 h-3.5" aria-hidden="true" />
            </button>
          </div>
        ) : (
          validation && !validation.valid && (
            <ValidationFeedback errors={validation.errors} fixPrompt={validation.fixPrompt} />
          )
        )}
      </div>

      {/* 4. Footer Actions */}
      <div className="p-6 sm:p-7 pt-4 bg-[#0d0f17] border-t border-white/8 flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          {onGoToPrompt && (
            <button
              type="button"
              onClick={onGoToPrompt}
              className="inline-flex items-center gap-1.5 text-xs text-zinc-400 hover:text-[#88BDA4] transition-colors font-medium cursor-pointer focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-[#88BDA4] rounded"
            >
              <ChevronLeft className="w-3.5 h-3.5" aria-hidden="true" />
              <span>Need to configure a prompt first? Back to Step 1</span>
            </button>
          )}
        </div>

        <button
          type="button"
          onClick={handleStart}
          disabled={!isValid}
          className={`inline-flex items-center justify-center gap-2 px-6 py-2.5 rounded-lg text-xs font-semibold tracking-wide transition-all shadow-md focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-[#88BDA4] ${
            isValid
              ? 'bg-[#88BDA4] hover:bg-[#9cd1b8] text-[#090A0F] active:scale-[0.98] cursor-pointer shadow-[#88BDA4]/20'
              : 'bg-[#171a24] text-zinc-500 border border-white/6 cursor-not-allowed opacity-60'
          }`}
        >
          <span>Open Workspace</span>
          <ArrowRight className="w-4 h-4" aria-hidden="true" />
        </button>
      </div>
    </div>
  );
}
